const translationKeys = new Set(Object.keys(translations.en));
Object.entries(translations).forEach(([language, dictionary]) => {
  const missingKeys = [...translationKeys].filter((key) => !Object.hasOwn(dictionary, key));
  const extraKeys = Object.keys(dictionary).filter((key) => !translationKeys.has(key));
  const mismatchedPlaceholders = [...translationKeys].filter((key) => {
    const englishPlaceholders = [...translations.en[key].matchAll(/\{(\w+)\}/g)]
      .map((match) => match[1])
      .sort()
      .join(',');
    const localizedPlaceholders = [...(dictionary[key] || '').matchAll(/\{(\w+)\}/g)]
      .map((match) => match[1])
      .sort()
      .join(',');
    return englishPlaceholders !== localizedPlaceholders;
  });

  if (missingKeys.length || extraKeys.length || mismatchedPlaceholders.length) {
    throw new Error(
      `Invalid ${language} translations. Missing: ${missingKeys.join(', ')}; ` +
      `extra: ${extraKeys.join(', ')}; placeholder mismatches: ${mismatchedPlaceholders.join(', ')}`
    );
  }
});

export default class LocalizationManager {
  constructor({ eventBus } = {}) {
    this.eventBus = eventBus;
    this.languageButtons = [...document.querySelectorAll('[data-language]')];
    this.language = this.getSavedLanguage();
    this.applyLanguage(this.language);

    this.languageButtons.forEach((button) => {
      button.addEventListener('click', () => {
        this.setLanguage(button.dataset.language);
      });
    });
  }

  getSavedLanguage() {
    let savedLanguage;
    try {
      savedLanguage = window.localStorage.getItem('portfolio-language');
    } catch (error) {
      if (error.name !== 'SecurityError') throw error;
      console.error('Could not read the saved language preference.', error);
      return 'en';
    }
    return Object.hasOwn(translations, savedLanguage) ? savedLanguage : 'en';
  }

  setLanguage(language) {
    if (!Object.hasOwn(translations, language)) {
      throw new RangeError(`Unsupported language: ${language}`);
    }

    this.language = language;
    this.applyLanguage(language);
    try {
      window.localStorage.setItem('portfolio-language', language);
    } catch (error) {
      if (error.name !== 'SecurityError') throw error;
      console.error('Could not save the language preference.', error);
    }
    this.eventBus?.emit('language:changed', language);
  }

  applyLanguage(language) {
    const dictionary = translations[language];
    document.documentElement.lang = language;
    document.title = dictionary['page.title'];

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = this.translate(element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((element) => {
      element.innerHTML = this.translate(element.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', this.translate(element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
      element.setAttribute('alt', this.translate(element.dataset.i18nAlt));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
      element.setAttribute('title', this.translate(element.dataset.i18nTitle));
    });

    this.languageButtons.forEach((button) => {
      const isSelected = button.dataset.language === language;
      button.setAttribute('aria-pressed', String(isSelected));
    });
  }

  translate(key, parameters = {}) {
    const message = translations[this.language][key];
    if (message === undefined) {
      throw new RangeError(`Missing translation: ${key} (${this.language})`);
    }

    return message.replace(/\{(\w+)\}/g, (placeholder, parameter) => {
      if (!Object.hasOwn(parameters, parameter)) {
        throw new RangeError(`Missing translation parameter: ${parameter} (${key})`);
      }
      return parameters[parameter];
    });
  }
}
